"""Generate app/src/corpus/types.ts from schema/corpus.sql (brief S9a #4; docs/PRODUCT.md
"Packages": app generates its types from the schema that ingest owns).

Run: python3 ingest/build/gen_types.py           write the file
     python3 ingest/build/gen_types.py --check   exit 1 when the file is stale

Column names, SQL types and nullability come from sqlite itself (the schema is executed into
an in-memory database and read back with PRAGMA table_info). The annotations the schema carries
as trailing comments (see the head of schema/corpus.sql) name the enum unions, mark booleans and
JSON columns, and become doc comments. Output follows the app's prettier settings (no
semicolons, single quotes, width 100) so `prettier --check` leaves it alone.
"""
import os
import re
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SCHEMA_PATH = os.path.join(ROOT, 'schema', 'corpus.sql')
OUT_PATH = os.path.join(ROOT, 'app', 'src', 'corpus', 'types.ts')
WIDTH = 100
SKIP_TABLES = re.compile(r'^(sqlite_|recipes_fts)')

_TABLE_RE = re.compile(r'CREATE TABLE (\w+) \((.*?)\n\)', re.S)
_COL_RE = re.compile(r'^\s*(\w+) (INTEGER|TEXT|REAL|BLOB)\b(.*)$')
_CHECK_RE = re.compile(r'CHECK \(\w+ IN \(([^)]*)\)\)')
_TYPE_RE = re.compile(r"^-- type (\w+): (.+)$", re.M)


def _split_comment(rest):
    """(sql part, comment) for the text after a column's type. A '--' inside quotes is not a
    comment start; the schema never has one, so the first '--' wins."""
    i = rest.find('--')
    return (rest, None) if i < 0 else (rest[:i], rest[i + 2:].strip())


def parse(schema_sql):
    """[(table, [column dict])] in schema order, and {enum name: [values]}."""
    con = sqlite3.connect(':memory:')
    con.executescript(schema_sql)
    version = con.execute("SELECT value FROM corpus_meta WHERE key = 'schema_version'").fetchone()[0]
    enums = {name: [v.strip().strip("'") for v in vals.split(',')] for name, vals in _TYPE_RE.findall(schema_sql)}
    tables = []
    for name, body in _TABLE_RE.findall(schema_sql):
        if SKIP_TABLES.match(name):
            continue
        info = {r[1]: r for r in con.execute(f'PRAGMA table_info({name})')}
        without_rowid = False
        cols = []
        for line in body.split('\n'):
            m = _COL_RE.match(line)
            if not m or m.group(1) in ('PRIMARY', 'CHECK', 'UNIQUE', 'FOREIGN'):
                continue
            col, sqltype, rest = m.groups()
            sql_part, comment = _split_comment(rest)
            _, _, _, _, _, pk = info[col][:6]
            notnull = bool(info[col][3]) or (pk > 0 and (sqltype == 'INTEGER' or without_rowid))
            kind, ts, doc = 'plain', {'INTEGER': 'number', 'REAL': 'number', 'TEXT': 'string',
                                      'BLOB': 'Uint8Array'}[sqltype], comment
            if comment and comment.startswith('enum:'):
                ename = comment.split(':', 1)[1].strip().split()[0]
                vals = [v.strip().strip("'") for v in _CHECK_RE.search(sql_part).group(1).split(',')]
                if ename in enums and enums[ename] != vals:
                    raise ValueError(f'enum {ename} has two different value lists')
                enums[ename] = vals
                kind, ts, doc = 'enum', ename, None
            elif comment and comment.startswith('bool'):
                kind, ts = 'bool', '0 | 1'
                doc = comment[4:].lstrip(': ').strip() or None
            elif comment and comment.startswith('json:'):
                jtype, _, jdoc = comment[5:].strip().partition(':')
                kind, ts = 'json', 'string'
                jdoc = jdoc.strip()
                doc = f'JSON-encoded `{jtype.strip()}`.' + (f' {jdoc[:1].upper()}{jdoc[1:]}' if jdoc else '')
            if pk > 0 and sqltype == 'TEXT' and 'PRIMARY KEY' in sql_part:
                notnull = True
            cols.append({'name': col, 'ts': ts, 'nullable': not notnull, 'doc': doc, 'kind': kind})
        # a TEXT primary key of a WITHOUT ROWID table is NOT NULL even without the words
        if re.search(rf'CREATE TABLE {name} \(.*?\n\) WITHOUT ROWID', schema_sql, re.S):
            pkcols = {r[1] for r in info.values() if r[5] > 0}
            for c in cols:
                if c['name'] in pkcols:
                    c['nullable'] = False
        tables.append((name, cols))
    con.close()
    return version, tables, enums


def _pascal(s):
    return ''.join(p[:1].upper() + p[1:] for p in s.split('_'))


def _upper_snake(s):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', s).upper()


def _array(prefix, items, suffix):
    one = prefix + '[' + ', '.join(items) + ']' + suffix
    if len(one) <= WIDTH:
        return [one]
    return [prefix + '['] + [f'  {i},' for i in items] + [']' + suffix]


def render(version, tables, enums):
    L = ['// GENERATED by ingest/build/gen_types.py from schema/corpus.sql. Do not edit by hand:',
         '// `ingest` owns the corpus schema (ruling R4); change schema/corpus.sql and regenerate.',
         '',
         '/** corpus_meta.schema_version this app was built against. */',
         f'export const CORPUS_SCHEMA_VERSION = {int(version)}',
         '']
    for ename in sorted(enums):
        const = f'{_upper_snake(ename)}_VALUES'
        L += _array(f'export const {const} = ', [f"'{v}'" for v in enums[ename]], ' as const')
        L.append(f'export type {ename} = (typeof {const})[number]')
        L.append('')
    for name, cols in tables:
        L.append(f'/** A row of `{name}`. */')
        L.append(f'export interface {_pascal(name)}Row {{')
        for c in cols:
            if c['doc']:
                L.append(f"  /** {c['doc']} */")
            L.append(f"  {c['name']}: {c['ts']}{' | null' if c['nullable'] else ''}")
        L.append('}')
        L.append('')
    return '\n'.join(L).rstrip('\n') + '\n'


def generate(schema_path=SCHEMA_PATH):
    with open(schema_path, encoding='utf-8') as fh:
        return render(*parse(fh.read()))


def main(argv):
    text = generate()
    if '--check' in argv:
        with open(OUT_PATH, encoding='utf-8') as fh:
            ok = fh.read() == text
        print('types.ts is up to date' if ok else 'types.ts is stale: run python3 ingest/build/gen_types.py')
        return 0 if ok else 1
    with open(OUT_PATH, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'wrote {OUT_PATH}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
